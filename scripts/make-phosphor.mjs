// Writes src/design/icons.gen.ts from Phosphor Bold (the only icon set the brand uses).
// Add a name to ICONS and run `npm run phosphor`. Only the path data is kept, so the app draws
// icons as real SVG elements and never injects markup.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const ICONS = [
  "arrow-left",
  "arrow-right",
  "arrow-clockwise",
  "film-strip",
  "gear-six",
  "house",
  "key",
  "magnifying-glass",
  "sign-out",
  "television-simple",
  "warning",
  "wrench",
];

const source = (name) =>
  fileURLToPath(new URL(`../node_modules/@phosphor-icons/core/assets/bold/${name}-bold.svg`, import.meta.url));

const lines = ICONS.map((name) => {
  const svg = readFileSync(source(name), "utf8");
  if (!svg.includes('viewBox="0 0 256 256"')) throw new Error(`${name}: unexpected viewBox`);
  const paths = [...svg.matchAll(/<path d="([^"]+)"\s*\/>/g)].map((match) => match[1]);
  const shapes = (svg.match(/<(?!\/|svg)[a-z]+/g) ?? []).length;
  if (paths.length === 0 || paths.length !== shapes) throw new Error(`${name}: has shapes other than plain paths`);
  return `  "${name}": ${JSON.stringify(paths.join(""))},`;
});

const out = `// Generated by scripts/make-phosphor.mjs from @phosphor-icons/core (Bold, MIT). Don't edit by hand.
export const icons = {
${lines.join("\n")}
} as const;

export type IconName = keyof typeof icons;
`;

writeFileSync(fileURLToPath(new URL("../src/design/icons.gen.ts", import.meta.url)), out);
console.log(`Wrote ${ICONS.length} icons`);
