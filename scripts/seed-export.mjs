// Turns the newest account export in scratch/ into src/letterboxd/seed.local.ts (git-ignored), so
// a build for your own TV starts with your history loaded and no upload is needed.
// Usage: npm run seed
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const scratch = fileURLToPath(new URL("../scratch/", import.meta.url));
const dirs = readdirSync(scratch).filter((name) => name.startsWith("export-")).sort();
const dir = dirs[dirs.length - 1];
if (!dir) throw new Error("No scratch/export-* folder found");

const read = (name) => {
  const file = `${scratch}${dir}/${name}.csv`;
  return existsSync(file) ? readFileSync(file, "utf8") : "";
};
const out = fileURLToPath(new URL("../src/letterboxd/seed.local.ts", import.meta.url));
const body = ["watched", "ratings", "diary", "watchlist"].map((name) => `  ${name}: ${JSON.stringify(read(name))},`).join("\n");
writeFileSync(out, `// Generated by scripts/seed-export.mjs from ${dir}. Personal data: git-ignored, never commit.\nexport const seed = {\n${body}\n};\n`);
console.log(`Wrote src/letterboxd/seed.local.ts from ${dir}`);
